package advisory

import (
	"github.com/prometheus/client_golang/prometheus"

	"github.com/angkaberapa/AAT/services/bnpb-ai-advisory/internal/core"
)

var (
	metricEvaluated = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "ai_advisory_events_total",
		Help: "Hazard events evaluated by the advisory detector.",
	}, []string{"result"})
	metricGenerated = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "ai_advisory_generated_total",
		Help: "Anomaly advisories generated by level.",
	}, []string{"level"})
	metricScore = prometheus.NewHistogram(prometheus.HistogramOpts{
		Name:    "ai_advisory_score",
		Help:    "Anomaly score of generated advisories.",
		Buckets: []float64{3.5, 4, 5, 7.5, 10, 20, 50},
	})
)

func init() {
	core.Metrics.MustRegister(metricEvaluated, metricGenerated, metricScore)
}
